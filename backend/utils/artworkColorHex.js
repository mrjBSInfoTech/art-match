export const normalizeHexCode = (value) => {
  const trimmed = String(value || "").trim();
  if (!HEX_COLOR_PATTERN.test(trimmed)) return null;
  const raw = trimmed.slice(1);
  const full =
    raw.length === 3
      ? [...raw].map((ch) => ch + ch).join("")
      : raw;
  return `#${full.toUpperCase()}`;
};

export const resolveColorNameToHex = (value) => {
  const trimmed = String(value || "").trim();
  if (!trimmed) return null;

  const directHex = normalizeHexCode(trimmed);
  if (directHex) return directHex;

  const embeddedHex = trimmed.match(/#(?:[0-9a-f]{6}|[0-9a-f]{3})\b/i)?.[0];
  if (embeddedHex) return normalizeHexCode(embeddedHex);

  const normalized = trimmed
    .toLowerCase()
    .replace(/[_/]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();

  if (EXACT_COLOR_HEX[normalized]) {
    return EXACT_COLOR_HEX[normalized];
  }

  for (const [keyword, hex] of COLOR_KEYWORDS) {
    if (new RegExp(`\\b${keyword}\\b`, "i").test(normalized)) {
      return hex;
    }
  }

  for (const [keyword, hex] of COLOR_KEYWORDS) {
    if (normalized.includes(keyword)) {
      return hex;
    }
  }

  return "#64748B";
};

export const parseColorTokens = (value) => {
  if (!value) return [];
  if (Array.isArray(value)) {
    return value.map((item) => String(item || "").trim()).filter(Boolean);
  }
  const str = String(value).trim();
  if (!str) return [];
  try {
    const parsed = JSON.parse(str);
    if (Array.isArray(parsed)) {
      return parsed.map((item) => String(item || "").trim()).filter(Boolean);
    }
  } catch {
    // Comma-separated string is the standard DB format.
  }
  return str
    .split(",")
    .map((item) => item.trim())
    .filter(Boolean);
};

export const hasNonHexColor = (value) => {
  const tokens = parseColorTokens(value);
  return tokens.some((token) => !HEX_COLOR_PATTERN.test(token));
};

export const colorNamesToHexString = (value) => {
  const tokens = parseColorTokens(value);
  if (!tokens.length) return "";
  const seen = new Set();
  const hexes = [];
  for (const token of tokens) {
    const hex = resolveColorNameToHex(token);
    if (hex && !seen.has(hex)) {
      seen.add(hex);
      hexes.push(hex);
    }
  }
  return hexes.join(", ");
};

export async function ensureHexArtworkColors(executor) {
  const [rows] = await executor.query(
    "SELECT artwork_id, color_used FROM artwork WHERE color_used IS NOT NULL AND TRIM(color_used) <> ''",
  );
  let updatedCount = 0;
  for (const row of rows || []) {
    if (!hasNonHexColor(row.color_used)) continue;
    const converted = colorNamesToHexString(row.color_used);
    if (converted && converted !== row.color_used) {
      await executor.query(
        "UPDATE artwork SET color_used = ? WHERE artwork_id = ?",
        [converted, row.artwork_id],
      );
      updatedCount += 1;
    }
  }
  return { checked: rows?.length || 0, updated: updatedCount };
}
