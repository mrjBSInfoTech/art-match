export function validateParcelPhotoCount(photos) {
  if (!Array.isArray(photos) || photos.length < 1 || photos.length > 5) {
    throw new Error("Upload 1 to 5 parcel photos before marking the order Packed");
  }
}

export function normalizeTrackingUrl(
  value,
  { required = false, httpsOnly = false, preserveInput = false } = {},
) {
  const trackingUrl = String(value || "").trim();
  if (!trackingUrl) {
    if (required) throw new Error("Add a courier tracking link before marking this order as shipped");
    return null;
  }
  if (trackingUrl.length > 2048) {
    throw new Error("Tracking link must be 2048 characters or fewer");
  }

  let parsedUrl;
  try {
    parsedUrl = new URL(trackingUrl);
  } catch {
    throw new Error("Enter a valid HTTP or HTTPS tracking link");
  }
  if (!["http:", "https:"].includes(parsedUrl.protocol) || (httpsOnly && parsedUrl.protocol !== "https:") ||
      !parsedUrl.hostname || parsedUrl.username || parsedUrl.password) {
    throw new Error(httpsOnly
      ? "Enter a valid HTTPS courier tracking link"
      : "Tracking link must use HTTP or HTTPS");
  }

  return preserveInput ? trackingUrl : parsedUrl.toString();
}

// Keep the authoritative carrier pages on the server. Sellers supply a unique
// Lalamove share link; the other couriers use their official tracking form.
const courierTrackingPages = new Map([
  ["lalamove", null],
  ["lbc", "https://www.lbcexpress.com/track/"],
  ["jnt", "https://www.jtexpress.ph/trajectoryQuery?flag=1"],
  ["ninjavan", "https://www.ninjavan.co/en-ph/tracking/"],
]);

export function normalizeShipmentTracking({ courier, trackingNumber, trackingUrl }) {
  if (typeof courier !== "string" || !courierTrackingPages.has(courier)) {
    throw new Error("Choose a supported courier before marking this order as shipped");
  }
  if (typeof trackingUrl !== "string") {
    throw new Error("Add a courier tracking link before marking this order as shipped");
  }
  const normalizedUrl = normalizeTrackingUrl(trackingUrl, {
    required: true,
    httpsOnly: true,
    preserveInput: true,
  });

  if (courier === "lalamove") {
    const hostname = new URL(normalizedUrl).hostname;
    if (hostname !== "lalamove.com" && !hostname.endsWith(".lalamove.com")) {
      throw new Error("Enter the HTTPS tracking/share link generated by Lalamove");
    }
    // Lalamove uses its share link, so a previous courier's number is discarded.
    return { courier, trackingNumber: null, trackingUrl: normalizedUrl };
  }

  if (typeof trackingNumber !== "string" || !trackingNumber.trim()) {
    throw new Error("Add a tracking number or ID for the selected courier");
  }
  if (/[\u0000-\u001f\u007f-\u009f]/.test(trackingNumber)) {
    throw new Error("Tracking number or ID must not contain control characters");
  }
  const normalizedNumber = trackingNumber.trim();
  if (normalizedNumber.length > 100) {
    throw new Error("Tracking number or ID must be 100 characters or fewer");
  }

  return {
    courier,
    trackingNumber: normalizedNumber,
    trackingUrl: courierTrackingPages.get(courier),
  };
}

export function getShippedNotificationTrackingUrl(
  notificationType,
  message,
  trackingUrl,
) {
  if (
    notificationType !== "shipping" ||
    !/has shipped(?: and is on the way|\. Tracking is now available in My Orders)\./i.test(String(message || ""))
  ) {
    return null;
  }
  return trackingUrl || null;
}

export function getPackedNotificationParcelPhotos(
  notificationType,
  message,
  photos,
) {
  if (
    notificationType !== "order_status" ||
    !/has been packed and is ready for shipment\./i.test(String(message || ""))
  ) {
    return [];
  }
  return photos;
}
